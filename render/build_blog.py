# -*- coding: utf-8 -*-
"""Builds blog covers (1200x675) + infographics (1200x900) + theme data file. Run: python3 build_blog.py"""
import os, json, asyncio, html
from playwright.async_api import async_playwright
from PIL import Image
from blog_articles import ARTICLES
ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
THEME = os.path.join(ROOT, "wp", "silent-talk-theme")
IMG = os.path.join(THEME, "assets", "img", "blog"); os.makedirs(IMG, exist_ok=True)
TMP = os.path.join(ROOT, "gen5", "src"); os.makedirs(TMP, exist_ok=True)
FONT = "file://" + os.path.join(THEME, "assets", "fonts", "Vazirmatn.woff2")
CSS = f"""@font-face{{font-family:V;src:url('{FONT}');font-weight:100 900}}
*{{box-sizing:border-box;margin:0;padding:0}}html,body{{font-family:V,sans-serif;direction:rtl}}.o{{color:#FF7A57}}"""

def crop_src(a):
    im = Image.open(os.path.join(ROOT, a["cover_src"])).convert("RGB")
    w, h = im.size; sc = 600 / w; im = im.resize((600, int(h * sc)), Image.LANCZOS)
    y = int(a["cover_y"] * max(0, im.height - 675)); im = im.crop((0, y, 600, y + 675))
    p = os.path.join(TMP, f"_crop_{a['slug']}.jpg"); im.save(p, quality=92); return p

def cover_html(a, p):
    return f"""<!doctype html><meta charset=utf-8><style>{CSS}
html,body{{width:1200px;height:675px;overflow:hidden;background:#14213D}}
.img{{position:absolute;left:0;top:0;width:600px;height:675px;background:url('file://{p}') center/cover}}
.img:after{{content:'';position:absolute;inset:0;background:linear-gradient(90deg,transparent 60%,#14213D)}}
.pan{{position:absolute;right:0;top:0;width:640px;height:675px;padding:56px 56px 50px 40px;color:#fff;display:flex;flex-direction:column}}
.cat{{align-self:flex-start;background:#E8431F;font-weight:800;font-size:24px;padding:6px 24px;border-radius:99px}}
h1{{font-size:49px;line-height:1.5;font-weight:900;margin-top:26px}}
.br{{margin-top:auto;font-size:26px;font-weight:700;display:flex;justify-content:space-between;align-items:center;opacity:.95}}
.br i{{display:inline-block;width:16px;height:16px;border-radius:50%;background:#E8431F;margin-left:10px}}.br span{{direction:ltr;color:#FF7A57}}
</style><div class=img></div><div class=pan><div class=cat>{html.escape(a['cat'])}</div><h1>{html.escape(a['title'])}</h1>
<div class=br><div><i></i>گفتگوهای خاموش</div><span>silenttalk.ir</span></div></div>"""

def info_html(a):
    li = "".join(f"<li><b>{i+1}</b><span>{html.escape(t)}</span></li>".replace(str(i+1), "۰۱۲۳۴۵۶۷۸۹"[i+1], 1) for i, t in enumerate(a["points"]))
    n = len(a["points"]); fs = 40 if n <= 5 else 35
    return f"""<!doctype html><meta charset=utf-8><style>{CSS}
html,body{{width:1200px;height:900px;overflow:hidden;background:#F6F1E7;color:#14213D}}
.w{{padding:54px 70px;height:100%;display:flex;flex-direction:column}}
.k{{font-size:26px;font-weight:800;color:#E8431F}}h2{{font-size:58px;font-weight:900;line-height:1.35;margin:6px 0 24px}}
ul{{list-style:none;display:flex;flex-direction:column;gap:14px}}li{{display:flex;align-items:center;gap:22px;background:#fff;border-radius:26px;padding:12px 26px;box-shadow:0 6px 0 #e2d8c3;font-size:{fs}px;font-weight:700;line-height:1.5}}
li b{{flex:none;width:58px;height:58px;border-radius:50%;background:#14213D;color:#fff;display:flex;align-items:center;justify-content:center;font-size:30px}}
.f{{margin-top:auto;display:flex;justify-content:space-between;font-size:26px;font-weight:700}}.f span{{direction:ltr;color:#E8431F}}
</style><div class=w><div class=k>خلاصهٔ مقاله</div><h2>{html.escape(a['info_title'])}</h2><ul>{li}</ul><div class=f><div>● گفتگوهای خاموش</div><span>silenttalk.ir</span></div></div>"""

async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(); pg = await b.new_page(viewport=dict(width=1200, height=900))
        for a in ARTICLES:
            for kind, h, size in (("cover", cover_html(a, crop_src(a)), (1200, 675)), ("info", info_html(a), (1200, 900))):
                f = os.path.join(TMP, f"_{kind}_{a['slug']}.html"); open(f, "w", encoding="utf-8").write(h)
                await pg.set_viewport_size(dict(width=size[0], height=size[1]))
                await pg.goto("file://" + f); await pg.wait_for_timeout(350)
                out = os.path.join(IMG, f"{a['slug']}-{kind}.jpg")
                await pg.screenshot(path=out + ".png"); Image.open(out + ".png").convert("RGB").save(out, quality=86, optimize=True); os.remove(out + ".png")
            print("ok", a["slug"])
        await b.close()
    data = [{k: a[k] for k in ("slug", "title", "cat", "desc", "excerpt", "tags", "body")} for a in ARTICLES]
    php = "<?php\nif (!defined('ABSPATH')) { exit; }\n// generated by render/build_blog.py\nfunction st_articles_data() {\n    return json_decode(<<<'JSON'\n" + json.dumps(data, ensure_ascii=False, indent=1) + "\nJSON\n, true);\n}\n"
    open(os.path.join(THEME, "inc", "articles-data.php"), "w", encoding="utf-8").write(php)
asyncio.run(main())
